// Turns supabase/seeds/quote_types.json into idempotent SQL for bk_quote_templates.
//
//   node scripts/seed-quote-types.mjs <user_id> > out.sql
//
// Re-running replaces the rows with the same (business_id, name), so editing the
// JSON and re-seeding updates the ready-written quote types without duplicating
// them. Quote types the user saved from the app under other names are untouched.
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const userId = process.argv[2];
if (!/^[0-9a-f-]{36}$/i.test(userId || "")) {
  console.error("usage: node scripts/seed-quote-types.mjs <user_id uuid>");
  process.exit(1);
}
const here = dirname(fileURLToPath(import.meta.url));
const seed = JSON.parse(readFileSync(join(here, "..", "supabase", "seeds", "quote_types.json"), "utf8"));

const q = (v) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => (v == null ? "null" : `${q(JSON.stringify(v))}::jsonb`);
const toItems = (items) => items.map((it) => (typeof it === "string"
  ? { description: it, note: "", qty: 1, rate: "" }
  : { description: it.description || "", note: it.note || "", qty: it.qty ?? 1, rate: it.rate ?? "" }));

const names = seed.templates.map((t) => q(t.name)).join(", ");
const rows = seed.templates.map((t) => [
  q(userId), q(seed.business_id), q(t.name), q(t.application_type), q(t.pricing_mode || "lump_sum"),
  j(toItems(t.items)), "null", q(Array.isArray(t.notes) ? t.notes.join("\n") : t.notes), "null", j(t.payment_plan),
].join(", "));

process.stdout.write(`-- generated by scripts/seed-quote-types.mjs — do not edit by hand
begin;
delete from public.bk_quote_templates where business_id = ${q(seed.business_id)} and name in (${names});
insert into public.bk_quote_templates (user_id, business_id, name, application_type, pricing_mode, items, lump_amount, notes, terms, payment_plan) values
${rows.map((r) => `  (${r})`).join(",\n")};
commit;
`);
